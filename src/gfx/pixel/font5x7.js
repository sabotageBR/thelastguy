// Letras acentuadas: base + marca.
const ACCENTS = {
  acute: ['...#.', '..#..'],
  grave: ['.#...', '..#..'],
  circ: ['..#..', '.#.#.'],
  tilde: ['.#.##', '##.#.'],
  diaer: ['.#.#.', '.....'],
};
const ACCENTED = {
  Á: ['A', 'acute'], À: ['A', 'grave'], Â: ['A', 'circ'], Ã: ['A', 'tilde'], Ä: ['A', 'diaer'],
  É: ['E', 'acute'], È: ['E', 'grave'], Ê: ['E', 'circ'],
  Í: ['I', 'acute'], Ì: ['I', 'grave'], Î: ['I', 'circ'],
  Ó: ['O', 'acute'], Ò: ['O', 'grave'], Ô: ['O', 'circ'], Õ: ['O', 'tilde'], Ö: ['O', 'diaer'],
  Ú: ['U', 'acute'], Ù: ['U', 'grave'], Û: ['U', 'circ'], Ü: ['U', 'diaer'],
  Ñ: ['N', 'tilde'],
};
const CEDILLA = ['..#..', '.#...'];

export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const LINE_TOP = 2; // espaço para acentos

/** Largura (px) do texto com espaçamento `sp` entre letras. */
export function textWidth(str, sp = 1) {
  const n = [...String(str)].length;
  return n ? n * (GLYPH_W + sp) - sp : 0;
}

/**
 * Chama plot(x, y) para cada pixel aceso do texto (maiúsculas), a partir de (x0, y0)
 * = canto superior esquerdo da linha (acentos usam y0..y0+1; letras y0+2..y0+8).
 */
export function textPixels(str, x0, y0, plot, sp = 1) {
  let x = x0;
  for (const raw of String(str).toUpperCase()) {
    let base = raw;
    let acc = null;
    let ced = false;
    if (ACCENTED[raw]) [base, acc] = ACCENTED[raw];
    else if (raw === 'Ç') {
      base = 'C';
      ced = true;
    }
    const g = G[base] || G['?'];
    for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (g[r][c] === '#') plot(x + c, y0 + LINE_TOP + r);
    if (acc) {
      const a = ACCENTS[acc];
      for (let r = 0; r < 2; r++) for (let c = 0; c < 5; c++) if (a[r][c] === '#') plot(x + c, y0 + r);
    }
    if (ced) for (let r = 0; r < 2; r++) for (let c = 0; c < 5; c++) if (CEDILLA[r][c] === '#') plot(x + c, y0 + LINE_TOP + 7 + r);
    x += GLYPH_W + sp;
  }
  return x - x0 - sp;
}
